/*
    傳回數值，四捨五入到指定的長度或有效位數
    FLOAT 或 REAL 格式欄位使用ROUND函數，請先轉換成 DECIMAL ，因為 FLOAT 與 REAL 都是近似值
    如果有效位數指定為負值，則會以[四捨五入 ]方式，進位到小數點前指定位數

    語法:ROUND([傳入值], [小數位元數])
*/
SELECT 'ROUND(123.444, 1)' AS 'SQL', ROUND(123.444, 1) AS 'Result'
UNION ALL SELECT 'ROUND(123.544, 1)', ROUND(123.544, 1)
UNION ALL SELECT 'ROUND(123.594, 1)', ROUND(123.594, 1)
UNION ALL SELECT 'ROUND(123.544, 2)', ROUND(123.544, 2)
UNION ALL SELECT 'ROUND(123.599, 2)', ROUND(123.599, 2)
UNION ALL SELECT 'ROUND(123.45, 0)', ROUND(123.45, 0)
UNION ALL SELECT 'ROUND(123.55, 0)', ROUND(123.55, 0)
UNION ALL SELECT 'ROUND(125.55, 0)', ROUND(125.55, 0)
UNION ALL SELECT 'ROUND(125.55,-1)', ROUND(125.55,-1)
